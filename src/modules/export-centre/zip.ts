/**
 * A minimal ZIP writer: stored (uncompressed) entries, UTF-8 names, CRC-32. Enough for a handful of small
 * files, and readable by every unzip tool. No dependency, and nothing is compressed that could go wrong.
 */
export interface ZipEntry {
  path: string
  bytes: Uint8Array
}

const TABLE = (() => {
  const t = new Uint32Array(256)
  for (let n = 0; n < 256; n++) {
    let c = n
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    t[n] = c >>> 0
  }
  return t
})()

export function crc32(bytes: Uint8Array): number {
  let c = 0xffffffff
  for (const b of bytes) c = TABLE[(c ^ b) & 0xff]! ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}

function dosDateTime(d: Date): { time: number; date: number } {
  const y = Math.max(1980, d.getUTCFullYear())
  return { time: (d.getUTCHours() << 11) | (d.getUTCMinutes() << 5) | (d.getUTCSeconds() >> 1), date: ((y - 1980) << 9) | ((d.getUTCMonth() + 1) << 5) | d.getUTCDate() }
}

export function createZip(entries: readonly ZipEntry[], when: Date): Uint8Array {
  const enc = new TextEncoder()
  const { time, date } = dosDateTime(when)
  const chunks: Uint8Array[] = []
  const central: Uint8Array[] = []
  let offset = 0
  const names = new Set<string>()
  for (const e of entries) {
    if (names.has(e.path)) throw new Error(`Duplicate path in archive: ${e.path}`)
    if (e.path.startsWith('/') || e.path.includes('..') || e.path.includes('\\')) throw new Error(`Unsafe path in archive: ${e.path}`)
    names.add(e.path)
    const name = enc.encode(e.path)
    const crc = crc32(e.bytes)
    const local = new DataView(new ArrayBuffer(30))
    local.setUint32(0, 0x04034b50, true)
    local.setUint16(4, 20, true)
    local.setUint16(6, 0x0800, true) // names are UTF-8
    local.setUint16(8, 0, true) // stored
    local.setUint16(10, time, true)
    local.setUint16(12, date, true)
    local.setUint32(14, crc, true)
    local.setUint32(18, e.bytes.length, true)
    local.setUint32(22, e.bytes.length, true)
    local.setUint16(26, name.length, true)
    local.setUint16(28, 0, true)
    chunks.push(new Uint8Array(local.buffer), name, e.bytes)

    const c = new DataView(new ArrayBuffer(46))
    c.setUint32(0, 0x02014b50, true)
    c.setUint16(4, 20, true)
    c.setUint16(6, 20, true)
    c.setUint16(8, 0x0800, true)
    c.setUint16(10, 0, true)
    c.setUint16(12, time, true)
    c.setUint16(14, date, true)
    c.setUint32(16, crc, true)
    c.setUint32(20, e.bytes.length, true)
    c.setUint32(24, e.bytes.length, true)
    c.setUint16(28, name.length, true)
    c.setUint32(42, offset, true)
    central.push(new Uint8Array(c.buffer), name)
    offset += 30 + name.length + e.bytes.length
  }
  const centralSize = central.reduce((n, c) => n + c.length, 0)
  const end = new DataView(new ArrayBuffer(22))
  end.setUint32(0, 0x06054b50, true)
  end.setUint16(8, entries.length, true)
  end.setUint16(10, entries.length, true)
  end.setUint32(12, centralSize, true)
  end.setUint32(16, offset, true)
  const all = [...chunks, ...central, new Uint8Array(end.buffer)]
  const out = new Uint8Array(all.reduce((n, c) => n + c.length, 0))
  let p = 0
  for (const c of all) {
    out.set(c, p)
    p += c.length
  }
  return out
}
