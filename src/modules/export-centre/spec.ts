import { catalogFontFor } from '@/modules/font-catalog/catalog'
import { assessRoleFit, KIND_LABEL, typefaceLimits } from '@/modules/brand-system/fit'
import { fontsInUse, ORIGIN_LABEL, resolveRole, roleSlugs } from '@/modules/brand-system/fonts'
import { assessProject } from '@/modules/brand-system/readiness'
import { mdInline, mdQuote } from '@/modules/brand-system/text'
import { brandName, PRIORITY_LABEL, TONE_LABEL, USE_CASE_LABEL } from '@/modules/brand-system/brand'
import { sizeSpec } from '@/modules/typography-system/scale'
import { typeStyles } from '@/modules/typography-system/tokens'
import { analyzeTypeface, describeCoverage } from '@/modules/font-validation/coverage'
import { computeScale, sizeForStep } from '@/modules/typography-system/scale'
import { fontPath } from './css'
import type { ExportInput } from './types'

const LEVEL_WORD = { blocks: 'Blocks', warns: 'Warning', info: 'Note' } as const

/** The typography specification as Markdown: what the system is, which font each role uses and why to trust it. */
export function buildSpec(input: ExportInput): string {
  const { project, revision, font } = input
  const face = project.customTypeface
  const L: string[] = []
  L.push(`# ${mdInline(brandName(project))}: typography specification`, '')
  L.push(`Generated by Tynovo from the saved project, revision \`${revision}\`, on ${input.generatedAt}.`, '')

  const brand = project.brand
  L.push('## Brand direction', '')
  if (brand.name.trim() && brand.name.trim() !== project.name) L.push(`Project: ${mdInline(project.name)}`, '')
  if (brand.description.trim()) L.push(mdQuote(brand.description.trim()), '')
  L.push(brand.personality.length > 0 ? `Personality: ${brand.personality.map(mdInline).join(', ')}.` : 'No personality words recorded.', '')
  if (brand.useCases.length > 0) L.push(`Use cases: ${brand.useCases.map((u) => USE_CASE_LABEL[u]).join(', ')}.`, '')
  if (brand.tones.length > 0) L.push(`Tone: ${brand.tones.map((t) => TONE_LABEL[t]).join(', ')}.`, '')
  L.push(`Priorities: readability ${PRIORITY_LABEL[brand.readabilityPriority]} (${brand.readabilityPriority} of 5), display use ${PRIORITY_LABEL[brand.displayPriority]} (${brand.displayPriority} of 5).`, '')
  if (brand.notes.trim()) L.push(mdQuote(brand.notes.trim()), '')

  const scale = project.typography.scale
  L.push('## Type scale', '', `Base size ${scale.baseSizePx}px, ratio ${scale.ratio}. Each step is the base size times the ratio to the power of its step number. rem values assume a 16px root.`, '')
  L.push('| Step | Size (px) | Size (rem) |', '| ---: | ---: | ---: |')
  const resp = project.typography.responsive
  for (const s of [...computeScale(scale)].reverse()) L.push(`| ${s.step} | ${s.sizePx} | ${Number((s.sizePx / 16).toFixed(4))} |`)
  L.push('')
  L.push(resp.enabled ? `Responsive sizing is on: sizes move from a ${resp.minBaseSizePx}px base with ratio ${resp.minRatio} at ${resp.minViewportPx}px wide to the main scale at ${resp.maxViewportPx}px wide. Sizes in the tables are the large-screen values.` : 'Responsive sizing is off: sizes are fixed.', '')
  L.push('### Heading and body sizes', '', '| Style | Scale step | Size (px) | Small-screen size (px) |', '| --- | ---: | ---: | ---: |')
  for (const t of typeStyles(project).filter((x) => x.kind !== 'role')) {
    const z = sizeSpec(project.typography, t.step)
    L.push(`| ${t.label} | ${t.step} | ${z.maxPx} | ${z.fluid ? z.minPx : 'same'} |`)
  }
  L.push('')

  L.push('## Roles', '')
  L.push('| Role | Used for | Font | Source | Size | Weight | Line height | Letter spacing |', '| --- | --- | --- | --- | ---: | ---: | ---: | ---: |')
  for (const r of project.typography.roles) {
    const f = resolveRole(project, r)
    L.push(`| ${mdInline(r.name)} | ${KIND_LABEL[r.kind]} | ${mdInline(f.origin === 'none' || f.origin === 'broken' ? '-' : f.family)} | ${ORIGIN_LABEL[f.origin]} | ${sizeForStep(scale, r.scaleStep)}px | ${r.weight} | ${r.lineHeight} | ${r.letterSpacingEm}em |`)
  }
  L.push('')
  const slugs = roleSlugs(project.typography.roles)
  L.push('CSS custom properties and classes for each role are in `typography.css` (for example `.type-' + (slugs.get(project.typography.roles[0]?.id ?? '') ?? 'display') + '`).', '')

  const uses = fontsInUse(project)
  L.push('## Fonts', '')
  if (uses.length === 0) L.push('No fonts are assigned to roles yet.', '')
  for (const u of uses) {
    const f = u.font
    L.push(`### ${mdInline(f.family)} (${ORIGIN_LABEL[f.origin]})`, '')
    L.push(`- Used by: ${u.roles.map((r) => mdInline(r.name)).join(', ')}`)
    L.push(`- CSS stack: \`${f.exportStack.replace(/`/g, '')}\``)
    L.push(`- Licence: ${f.license ? `${mdInline(f.license.name)}${f.license.spdx ? ` (${mdInline(f.license.spdx)})` : ''}${f.license.verified ? '' : ', not verified'}` : 'not recorded'}`)
    if (f.origin === 'custom' && face) {
      L.push(`- Origin: an original typeface designed in this project (${face.dna.family} construction family).`)
      L.push(font ? `- Font file: \`${fontPath(font.filename)}\`, included in the package.` : '- Font file: not available (the typeface has errors that block export).')
      L.push(`- ${describeCoverage(analyzeTypeface(face))}`)
      L.push('- What it does not do:')
      for (const l of typefaceLimits(face)) L.push(`  - ${mdInline(l)}`)
    } else {
      const cat = f.source?.kind === 'catalog' ? catalogFontFor(f.source.family) : undefined
      L.push('- The font file is **not included** in this export. Supply it separately.')
      if (cat) L.push(`- Available from the ${cat.distribution} package (version ${cat.distributionVersion}); published upstream at ${cat.upstream}. Weights bundled in Tynovo: ${cat.weights.join(', ')}.`)
      else if (f.source?.kind === 'system') L.push('- Named by you. It renders only where it is installed; elsewhere the fallback is used.')
    }
    L.push('')
  }

  const withFit = project.typography.roles.filter((r) => face && resolveRole(project, r).origin === 'custom')
  if (face && withFit.length > 0) {
    L.push('## Custom typeface fit', '')
    for (const r of withFit) {
      const fit = assessRoleFit(face, r, sizeForStep(scale, r.scaleStep))
      L.push(`- **${mdInline(r.name)}**: ${fit.verdict === 'suitable' ? 'suitable' : fit.verdict === 'caution' ? 'use with care' : 'not appropriate'}.`)
      for (const f of fit.findings) L.push(`  - ${LEVEL_WORD[f.level === 'blocks' ? 'blocks' : f.level === 'warns' ? 'warns' : 'info']}: ${mdInline(f.message)}`)
    }
    L.push('')
  }

  const issues = assessProject(project)
  L.push('## Checks at export time', '')
  if (issues.length === 0) L.push('No issues found.', '')
  else {
    for (const i of issues) L.push(`- ${LEVEL_WORD[i.level]}: ${mdInline(i.message)}`)
    L.push('')
  }
  return L.join('\n')
}
