import { useEffect } from 'react'
import { APP_DESCRIPTION, headTags, pageTitle, type PageMeta } from './seo-config'
import { SITE_URL } from './site-url'

const OG_IMAGE = {
  ogImagePath: '/og.png',
  ogImageAlt: 'The word HOTEL set in a geometric typeface generated by Tynovo.',
}

/** Every tag this component owns, whether it came from the pre-rendered HTML or a previous route. */
const OWNED = 'meta[name="description"], meta[name="robots"], meta[name^="twitter:"], meta[property^="og:"], link[rel="canonical"]'

/** Sets title and head tags for the current route. Static HTML is also pre-rendered per route at build time. */
export function Seo({ page }: { page: Pick<PageMeta, 'path' | 'title' | 'description' | 'indexable'> }) {
  const { path, title, description, indexable } = page
  useEffect(() => {
    const full = pageTitle(title)
    document.title = full
    document.head.querySelectorAll(OWNED).forEach((el) => el.remove())
    for (const t of headTags({ path, title: full, description, indexable }, { siteUrl: SITE_URL, ...OG_IMAGE })) {
      const el = document.createElement(t.tag)
      if (t.tag === 'meta') {
        el.setAttribute(t.attr, t.key)
        el.setAttribute('content', t.content)
      } else {
        el.setAttribute('rel', t.rel)
        el.setAttribute('href', t.href)
      }
      document.head.append(el)
    }
  }, [path, title, description, indexable])
  return null
}

/** Metadata for application routes: never indexed. */
export function AppSeo({ title }: { title: string }) {
  return <Seo page={{ path: '/app', title, description: APP_DESCRIPTION, indexable: false }} />
}
