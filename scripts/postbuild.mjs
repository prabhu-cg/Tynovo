// Runs after `vite build`: pre-renders per-route <head> metadata into static HTML, and writes sitemap.xml and robots.txt.
// Needs Node >= 23.6 (imports the shared TypeScript config directly).
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { loadEnv } from 'vite'
import { applyMeta, buildRobots, buildSitemap, normalizeSiteUrl, PUBLIC_PAGES } from '../src/modules/marketing/seo-config.ts'

const dist = new URL('../dist/', import.meta.url).pathname
const env = loadEnv(process.env.MODE ?? 'production', process.cwd(), 'VITE_')
const siteUrl = normalizeSiteUrl(process.env.VITE_SITE_URL ?? env.VITE_SITE_URL)

const template = readFileSync(join(dist, 'index.html'), 'utf8')

// Preload the Latin Manrope file: it is on the critical path of every page.
const assets = readdirSync(join(dist, 'assets'))
const manrope = assets.find((f) => /^manrope-latin-wght-normal-.*\.woff2$/.test(f))
const preload = manrope ? `    <link rel="preload" as="font" type="font/woff2" crossorigin href="/assets/${manrope}" />\n  </head>` : null

const opts = {
  siteUrl,
  ogImagePath: '/og.png',
  ogImageAlt: 'The word HOTEL set in a geometric typeface generated by Brand Typography Studio.',
}

for (const page of PUBLIC_PAGES) {
  let html = applyMeta(template, page, opts)
  if (preload) html = html.replace('</head>', preload)
  const out = page.path === '/' ? join(dist, 'index.html') : join(dist, page.path.slice(1), 'index.html')
  mkdirSync(join(out, '..'), { recursive: true })
  writeFileSync(out, html)
}

writeFileSync(join(dist, 'robots.txt'), buildRobots(siteUrl))
if (siteUrl) {
  writeFileSync(join(dist, 'sitemap.xml'), buildSitemap(siteUrl))
  console.log(`postbuild: ${PUBLIC_PAGES.length} pages, sitemap.xml and robots.txt written for ${siteUrl}`)
} else {
  console.warn('postbuild: VITE_SITE_URL is not set. Canonical/OG URLs and sitemap.xml were skipped. Set it for production deploys.')
}
if (!existsSync(join(dist, 'og.png'))) console.warn('postbuild: public/og.png is missing; og:image will 404.')
