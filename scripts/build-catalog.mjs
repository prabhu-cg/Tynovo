// Builds src/modules/font-catalog/catalog.data.ts from the metadata that ships inside each installed
// @fontsource/<id> package (family, category, weights, styles, licence, copyright, version, upstream source).
// Nothing is typed by hand and nothing is fetched: run `npm run catalog` after changing IDS or updating a package.
// The unit test `catalog.test.ts` re-reads the same files and fails if the generated data has drifted.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const IDS = [
  // Sans serif
  'inter', 'manrope', 'dm-sans', 'work-sans', 'ibm-plex-sans', 'source-sans-3', 'nunito-sans', 'public-sans', 'space-grotesk',
  'montserrat', 'poppins', 'raleway', 'open-sans', 'lato', 'rubik', 'karla', 'outfit', 'plus-jakarta-sans', 'figtree', 'jost', 'lexend',
  // Serif
  'fraunces', 'playfair-display', 'lora', 'merriweather', 'source-serif-4', 'ibm-plex-serif', 'libre-baskerville', 'eb-garamond', 'dm-serif-display',
  'cormorant-garamond', 'crimson-pro', 'spectral', 'bitter', 'noto-serif', 'pt-serif', 'newsreader',
  // Monospace
  'ibm-plex-mono', 'jetbrains-mono', 'space-mono', 'fira-code', 'inconsolata', 'dm-mono',
  // Display
  'bebas-neue', 'abril-fatface', 'oswald', 'anton', 'archivo-black', 'syne',
  // Handwriting
  'caveat', 'dancing-script', 'pacifico',
]
/** Weights Tynovo bundles (latin subset, upright), where the family has them. Regular italic is bundled where it exists. */
const WEIGHTS = [300, 400, 500, 600, 700, 800, 900]
const OFL_URL = 'https://openfontlicense.org/open-font-license-official-text/'

const out = []
for (const id of IDS) {
  const dir = `node_modules/@fontsource/${id}`
  const m = JSON.parse(readFileSync(`${dir}/metadata.json`, 'utf8'))
  const pkg = JSON.parse(readFileSync(`${dir}/package.json`, 'utf8'))
  if (m.license.type !== 'OFL-1.1') throw new Error(`${id}: licence is ${m.license.type}; only OFL-1.1 fonts are catalogued`)
  const have = (w, style) => existsSync(`${dir}/files/${id}-latin-${w}-${style}.woff2`)
  const weights = WEIGHTS.filter((w) => m.weights.includes(w) && have(w, 'normal'))
  if (!weights.includes(400)) throw new Error(`${id}: no regular weight`)
  out.push({
    id,
    family: m.family,
    category: m.category,
    weights,
    styles: m.styles,
    italic: m.styles.includes('italic') && have(400, 'italic'),
    license: { spdx: m.license.type, url: OFL_URL, copyright: m.license.attribution.split(/\s\S+\.(?:ttf|otf):/)[0].trim() },
    version: m.version,
    upstream: m.source,
    distribution: `@fontsource/${id}`,
    distributionVersion: pkg.version,
    page: `https://fontsource.org/fonts/${id}`,
  })
}
out.sort((a, b) => a.family.localeCompare(b.family))
const header = `// GENERATED by scripts/build-catalog.mjs from node_modules/@fontsource/*/metadata.json. Do not edit by hand.\n`
writeFileSync('src/modules/font-catalog/catalog.data.ts', `${header}import type { CatalogEntry } from './types'\n\nexport const CATALOG_DATA: readonly CatalogEntry[] = ${JSON.stringify(out, null, 2)}\n`)
console.log(`Wrote ${out.length} fonts`)
